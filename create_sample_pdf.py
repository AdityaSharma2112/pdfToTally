def generate_sample_pdf(output_path="sbi_sample_statement.pdf"):
    doc = fitz.open()
    for text_page in pdf_text_pages:
        page = doc.new_page(width=595, height=842) # A4
        rect = fitz.Rect(30, 40, 565, 800)
        page.insert_textbox(rect, text_page, fontsize=9, fontname="helv")
    doc.save(output_path)
    doc.close()
    print(f"Sample PDF created at {output_path}")

